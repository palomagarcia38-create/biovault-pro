const fs=require('node:fs');
const {initializeTestEnvironment,assertFails,assertSucceeds}=require('@firebase/rules-unit-testing');
const {doc,setDoc,getDoc,getDocs,collection,deleteDoc}=require('firebase/firestore');
const assert=require('node:assert/strict');
(async()=>{
  const env=await initializeTestEnvironment({projectId:'demo-biovault',firestore:{host:'127.0.0.1',port:8081,rules:fs.readFileSync('firestore.rules','utf8')}});
  let passed=0;
  try {
    const alice=env.authenticatedContext('alice').firestore(),bob=env.authenticatedContext('bob').firestore(),anon=env.unauthenticatedContext().firestore();
    const reading={date:'2026-11-20',weight:65,height:165,personId:'alice',personName:'Synthetic Alice'};
    await assertSucceeds(setDoc(doc(alice,'users/alice/measurements/a'),reading));passed++;
    await assertSucceeds(getDoc(doc(alice,'users/alice/measurements/a')));passed++;
    await assertSucceeds(getDocs(collection(alice,'users/alice/measurements')));passed++;
    await assertFails(getDoc(doc(bob,'users/alice/measurements/a')));passed++;
    await assertFails(getDocs(collection(bob,'users/alice/measurements')));passed++;
    await assertFails(setDoc(doc(bob,'users/alice/measurements/a'),reading));passed++;
    await assertFails(deleteDoc(doc(bob,'users/alice/measurements/a')));passed++;
    await assertFails(getDoc(doc(anon,'users/alice/measurements/a')));passed++;
    await assertFails(setDoc(doc(anon,'users/alice/measurements/a'),reading));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/measurements/wrong'),{...reading,personId:'bob'}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/measurements/invalid'),{...reading,weight:-1}));passed++;
    await assertSucceeds(setDoc(doc(alice,'users/alice/profile/main'),{name:'Synthetic Alice',personId:'alice',sex:'F',age:28,height:165}));passed++;
    await assertFails(getDoc(doc(bob,'users/alice/profile/main')));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/profile/main'),{name:'X',personId:'alice',admin:true}));passed++;
    await assertFails(getDocs(collection(alice,'measurements')));passed++;
    await assertFails(getDocs(collection(anon,'measurements')));passed++;
    await assertFails(setDoc(doc(alice,'measurements/legacy'),reading));passed++;
    await assertSucceeds(getDoc(doc(anon,'clinical_knowledge/biovault-v4-4')));passed++;
    const goal={schema:2,objective:'lose_weight',targets:{weight:60,fat:25,muscle:32,visceral:null},baseline:null,deadline:'2027-02-20',startedAt:'2026-11-20',updatedAt:'2026-11-20',history:[],dismissed:false};
    await assertSucceeds(setDoc(doc(alice,'users/alice/goals/active'),goal));passed++;
    await assertSucceeds(getDoc(doc(alice,'users/alice/goals/active')));passed++;
    await assertFails(getDoc(doc(bob,'users/alice/goals/active')));passed++;
    await assertFails(setDoc(doc(bob,'users/alice/goals/active'),goal));passed++;
    await assertFails(getDoc(doc(anon,'users/alice/goals/active')));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/goals/active'),{...goal,targets:{weight:-1}}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/goals/active'),{...goal,admin:true}));passed++;
    await assertSucceeds(setDoc(doc(alice,'users/alice/goals/active'),{schema:2,dismissed:true,objective:null,targets:{},baseline:null,deadline:null,startedAt:'2026-11-20',updatedAt:'2026-11-20'}));passed++;
    const general={...reading,weight:180,measurementSchema:2,equipment:'Equipamento clínico',muscle:65,muscleUnit:'kg',muscleKind:'skeletal',visceral:105.5,visceralUnit:'cm2',notes:'Transcrição sintética'};
    await assertSucceeds(setDoc(doc(alice,'users/alice/measurements/general'),general));passed++;
    await assertFails(getDoc(doc(bob,'users/alice/measurements/general')));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/measurements/badunit'),{...general,muscleUnit:'lb'}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/measurements/badmass'),{...general,muscle:181}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/measurements/badweight'),{...general,weight:501}));passed++;
    await assertSucceeds(setDoc(doc(alice,'users/alice/measurements/optional'),{...general,equipment:null,muscle:null,visceral:null}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/measurements/toolong'),{...general,notes:'x'.repeat(2001)}));passed++;
    await assertSucceeds(setDoc(doc(alice,'users/alice/goals/active'),{...goal,targets:{weight:180}}));passed++;
    const unitGoal={...goal,units:{muscle:'kg',visceral:'cm2'},muscleKind:'skeletal',targets:{muscle:65,visceral:100}};
    await assertSucceeds(setDoc(doc(alice,'users/alice/goals/active'),unitGoal));passed++;
    await assertFails(setDoc(doc(bob,'users/alice/goals/active'),unitGoal));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/goals/active'),{...unitGoal,units:{muscle:'lb'}}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/goals/active'),{...unitGoal,units:'kg'}));passed++;
    const training={schema:1,kind:'session',data:JSON.stringify({id:'example'}),updatedAt:Date.now(),revision:'example'};
    await assertSucceeds(setDoc(doc(alice,'users/alice/training/session_example'),training));passed++;
    await assertSucceeds(getDoc(doc(alice,'users/alice/training/session_example')));passed++;
    await assertFails(getDoc(doc(bob,'users/alice/training/session_example')));passed++;
    await assertFails(getDocs(collection(bob,'users/alice/training')));passed++;
    await assertFails(setDoc(doc(bob,'users/alice/training/session_example'),training));passed++;
    await assertFails(setDoc(doc(anon,'users/alice/training/session_example'),training));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/training/invalid'),{...training,admin:true}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/training/invalid'),{...training,data:'x'.repeat(300001)}));passed++;
    await assertFails(setDoc(doc(alice,'users/alice/training/invalid'),{...training,kind:'admin'}));passed++;
    await assertFails(deleteDoc(doc(bob,'users/alice/training/session_example')));passed++;
    assert.equal((await getDoc(doc(alice,'users/alice/measurements/a'))).data().weight,65);passed++;
    console.log(JSON.stringify({passed,project:'demo-biovault',productionWrites:0}));
  }finally{await env.cleanup();}
})().catch(error=>{console.error(error);process.exitCode=1;});
